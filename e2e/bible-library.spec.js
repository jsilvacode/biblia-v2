import { expect, test } from '@playwright/test'

async function openOldTestament(page) {
  await page.goto('/bible')
  await page.getByRole('button', { name: /Antiguo Testamento/ }).click()
  await expect(page.getByRole('button', { name: /Antiguo Testamento/ })).toHaveAttribute('aria-pressed', 'true')
}

test('all 66 books remain in canonical order within their literary collections', async ({ page }) => {
  await openOldTestament(page)
  const books = page.locator('[data-book-id]')
  await expect(books).toHaveCount(39)
  expect(await books.evaluateAll(elements => elements.map(element => Number(element.dataset.bookId))))
    .toEqual(Array.from({ length: 39 }, (_, index) => index + 1))
  await expect(page.getByRole('region', { name: 'Pentateuco', exact: true }).locator('[data-book-id]')).toHaveCount(5)
  await expect(page.getByRole('region', { name: 'Históricos', exact: true }).locator('[data-book-id]')).toHaveCount(12)
  await expect(page.getByRole('region', { name: 'Poéticos y sapienciales', exact: true }).locator('[data-book-id]')).toHaveCount(5)
  await expect(page.getByRole('region', { name: 'Profetas mayores', exact: true }).locator('[data-book-id]')).toHaveCount(5)
  await expect(page.getByRole('region', { name: 'Profetas menores', exact: true }).locator('[data-book-id]')).toHaveCount(12)

  await page.getByRole('button', { name: /Nuevo Testamento/ }).click()
  await expect(books).toHaveCount(27)
  expect(await books.evaluateAll(elements => elements.map(element => Number(element.dataset.bookId))))
    .toEqual(Array.from({ length: 27 }, (_, index) => index + 40))
  await expect(page.getByRole('region', { name: 'Evangelios', exact: true }).locator('[data-book-id]')).toHaveCount(4)
  await expect(page.getByRole('region', { name: 'Históricos', exact: true }).locator('[data-book-id]')).toHaveCount(1)
  await expect(page.getByRole('region', { name: 'Cartas paulinas', exact: true }).locator('[data-book-id]')).toHaveCount(13)
  await expect(page.getByRole('region', { name: 'Cartas generales', exact: true }).locator('[data-book-id]')).toHaveCount(8)
  await expect(page.getByRole('region', { name: 'Profecía', exact: true }).locator('[data-book-id]')).toHaveCount(1)
})

test('choosing a book opens its chapters in a centred modal and goes directly to reading', async ({ page }) => {
  const corpusRequests = []
  page.on('request', request => {
    if (new URL(request.url()).pathname.startsWith('/data/')) corpusRequests.push(request.url())
  })
  await openOldTestament(page)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.locator('[data-book-id="1"]').click()
  const dialog = page.getByRole('dialog', { name: 'Génesis', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('link')).toHaveCount(50)
  const box = await dialog.boundingBox()
  const viewport = page.viewportSize()
  expect(box.width).toBeLessThanOrEqual(480)
  expect(Math.abs(box.x + box.width / 2 - viewport.width / 2)).toBeLessThan(2)
  expect(Math.abs(box.y + box.height / 2 - viewport.height / 2)).toBeLessThan(2)
  expect(corpusRequests).toEqual([])
  await dialog.getByRole('link', { name: '2', exact: true }).click()
  await expect(page).toHaveURL(/\/read\/1\/2$/)
  await expect(page.locator('#verse-1')).toBeVisible()
  expect(corpusRequests.length).toBeGreaterThan(0)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.locator('#root')).not.toHaveAttribute('aria-hidden', 'true')
})

test('long chapter lists stay inside a small screen and preserve list position and focus on close', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 568 })
  await openOldTestament(page)
  const book = page.locator('[data-book-id="19"]')
  await book.scrollIntoViewIfNeeded()
  const scrollBefore = await page.evaluate(() => scrollY)
  await book.click()
  const dialog = page.getByRole('dialog', { name: 'Salmos', exact: true })
  await expect(dialog.getByRole('link')).toHaveCount(150)
  const box = await dialog.boundingBox()
  expect(box.x).toBeGreaterThanOrEqual(16)
  expect(box.y).toBeGreaterThanOrEqual(16)
  expect(box.x + box.width).toBeLessThanOrEqual(304)
  expect(box.y + box.height).toBeLessThanOrEqual(552)
  await dialog.getByRole('link', { name: '150', exact: true }).scrollIntoViewIfNeeded()
  await expect(dialog.getByRole('link', { name: '150', exact: true })).toBeInViewport()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(book).toBeFocused()
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(scrollBefore)

  await book.click()
  await page.locator('.reader-dialog-backdrop').click({ position: { x: 4, y: 4 } })
  await expect(dialog).toHaveCount(0)
  await expect(book).toBeFocused()
})

test('a book found by name keeps its search after closing the chapter modal', async ({ page }) => {
  await page.goto('/bible')
  const search = page.getByRole('searchbox')
  await search.fill('salmos')
  const book = page.locator('[data-book-id="19"]')
  await book.click()
  const dialog = page.getByRole('dialog', { name: 'Salmos', exact: true })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Cerrar', exact: true }).click()
  await expect(search).toHaveValue('salmos')
  await expect(book).toBeFocused()
  await book.press('Enter')
  const input = dialog.getByRole('spinbutton', { name: 'Ir al capítulo' })
  await input.fill('151')
  await expect(dialog.getByRole('button', { name: 'Abrir', exact: true })).toBeDisabled()
  await input.fill('150')
  await input.press('Enter')
  await expect(page).toHaveURL(/\/read\/19\/150$/)
  await expect(page.locator('#verse-1')).toBeVisible()
})
