import { expect, test } from '@playwright/test'

const close = (surface) => surface.getByRole('button', { name: 'Cerrar', exact: true })

async function expectCloseAtRight(surface) {
  // Read both rectangles in one frame while anchored panels find their position.
  await expect.poll(() => surface.evaluate((element) => {
    const panel = element.getBoundingClientRect()
    const button = [...element.querySelectorAll('button')].find(control => control.getAttribute('aria-label') === 'Cerrar')?.getBoundingClientRect()
    return Boolean(button && button.x > panel.x + panel.width / 2 && button.y < panel.y + 65 && button.width >= 40)
  })).toBe(true)
  await expect(close(surface).locator('svg.lucide-x')).toHaveCount(1)
}

test('Home matches the approved simple picker and recent readings without repeated arrows', async ({ page }) => {
  await page.addInitScript(() => {
    const readings = [{ book: 3, chapter: 5, verse: 1, updatedAt: 300 }, { book: 47, chapter: 1, verse: 15, updatedAt: 200 }, { book: 18, chapter: 14, verse: 1, updatedAt: 100 }]
    localStorage.setItem('santa_biblia_v2_recent_readings', JSON.stringify(readings))
    localStorage.setItem('santa_biblia_v2_reading', JSON.stringify(readings[0]))
  })
  await page.goto('/')
  const panel = page.getByTestId('home-reading-panel')
  await expect(panel.getByText('Elige un libro y capítulo', { exact: true })).toBeVisible()
  const isMobile = page.viewportSize().width <= 620
  const recent = panel.getByRole('region', { name: isMobile ? 'Última lectura' : 'Lecturas recientes', exact: true })
  await expect(recent.getByRole('link')).toHaveCount(isMobile ? 1 : 3)
  await expect(recent.locator('a')).toHaveCount(3)
  await expect(recent.locator('a svg')).toHaveCount(0)
  const picker = panel.getByTestId('home-reading-actions')
  await expect(picker.getByRole('button')).toHaveCount(1)
  await picker.getByRole('button', { name: 'Seleccionar libro', exact: true }).click()
  const menu = picker.getByRole('dialog')
  await expectCloseAtRight(menu)
  await menu.locator('[data-book-id="43"]').click()
  await expect(menu.locator('[data-chapter]')).toHaveCount(21)
  await menu.locator('[data-book-id="43"]').click()
  await expect(menu.locator('[data-chapter]')).toHaveCount(0)
  await menu.locator('[data-book-id="43"]').click()
  await menu.getByRole('button', { name: 'Cerrar: Juan' }).click()
  await expect(menu.locator('[data-chapter]')).toHaveCount(0)
  await close(menu).click()
  await expect(menu).toHaveCount(0)
  await recent.getByRole('link', { name: /Continuar(?:\b|:)/ }).click()
  await expect(page).toHaveURL(/\/read\/3\/5\/1$/)
})

test('reader shows the approved book heading and searches books and exact citations in place', async ({ page }) => {
  const workers = []
  page.on('worker', worker => workers.push(worker.url()))
  await page.goto('/read/43/3')
  await expect(page.locator('.reader-chapter-version')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Juan', exact: true })).toBeVisible()
  await expect(page.locator('.reader-chapter-number')).toHaveText('Capítulo 3')
  const row = page.getByTestId('reader-passage-row')
  const input = row.getByRole('searchbox')
  const openSearch = async () => {
    if (page.viewportSize().width < 768) {
      const trigger = row.getByRole('button', { name: 'Búsqueda rápida', exact: true })
      await expect(trigger).toHaveAttribute('aria-expanded', 'false')
      await trigger.click()
      await expect(input).toBeFocused()
    }
  }
  await expect(row.getByRole('button', { name: 'Volver', exact: true })).toBeVisible()
  await openSearch()
  await input.fill('Juan')
  const results = row.getByRole('region', { name: 'Resultados de búsqueda', exact: true })
  await expectCloseAtRight(results)
  expect(workers).toEqual([])
  await close(results).click()
  await expect(results).toHaveCount(0)
  await expect(input).toBeFocused()
  await input.fill('Juan 3:16')
  await input.press('Enter')
  await expect(page).toHaveURL(/\/read\/43\/3\/16$/)
  await expect(page.locator('#verse-16')).toBeVisible()
  await openSearch()
  await expect(input).toHaveValue('')
  await input.fill('Salmos')
  await row.getByRole('button', { name: 'Buscar', exact: true }).click()
  const chapters = page.getByRole('dialog', { name: 'Salmos', exact: true })
  await expectCloseAtRight(chapters)
  await chapters.getByRole('link', { name: '150', exact: true }).click()
  await expect(page).toHaveURL(/\/read\/19\/150$/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

test('modal X closes while a nested back arrow returns to the actual previous panel', async ({ page }) => {
  await page.goto('/read/43/3/16')
  await page.locator('#verse-16').click()
  const actions = page.getByRole('dialog', { name: 'Acciones del versículo', exact: true })
  await expectCloseAtRight(actions)
  await expect(actions.getByRole('button', { name: 'Volver', exact: true })).toHaveCount(0)
  await actions.getByRole('button', { name: 'Ver comentario bíblico', exact: true }).click()
  const commentary = page.getByRole('dialog', { name: 'Comentario bíblico', exact: true })
  await expectCloseAtRight(commentary)
  await commentary.getByRole('button', { name: 'Volver', exact: true }).click()
  await expect(actions).toBeVisible()
  await actions.getByRole('button', { name: 'Ver comentario bíblico', exact: true }).click()
  await close(commentary).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: 'Abrir menú de lectura', exact: true }).click()
  const menu = page.getByRole('dialog', { name: 'Opciones rápidas', exact: true })
  await expectCloseAtRight(menu)
  await menu.getByRole('button', { name: 'Todos los ajustes', exact: true }).click()
  const settings = page.getByRole('dialog', { name: 'Ajustes', exact: true })
  await expectCloseAtRight(settings)
  await settings.getByRole('button', { name: 'Volver', exact: true }).click()
  await expect(menu).toBeVisible()
  await close(menu).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

test('category and situation dropdowns close with X without changing the selection', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/bible')
  const category = page.getByRole('combobox', { name: 'Filtrar libros', exact: true })
  await category.click()
  await close(page.locator('[class*="menu"]').filter({ has: page.getByRole('listbox') }).last()).click()
  await expect(page.getByRole('listbox')).toHaveCount(0)
  await expect(category).toContainText('Todos los libros')
  await expect(category).toBeFocused()
  await page.goto('/topics')
  const situation = page.getByRole('combobox', { name: 'Situación', exact: true })
  await situation.click()
  await page.getByRole('button', { name: 'Cerrar', exact: true }).click()
  await expect(page.getByRole('listbox')).toHaveCount(0)
  await expect(situation).toBeFocused()
})
