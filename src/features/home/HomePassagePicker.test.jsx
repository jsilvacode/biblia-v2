import { act, cleanup, fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { HomePassagePicker } from './HomePassagePicker'

vi.mock('../../i18n', () => ({ useI18n: () => ({ locale: 'es', t: (key, values = {}) => ({
  'home.selectBook': 'Seleccionar libro', 'home.chooseReading': 'Elegir una lectura',
  'common.close': 'Cerrar', 'bible.oldTestament': 'Antiguo Testamento', 'bible.newTestament': 'Nuevo Testamento',
  'bible.chapters': 'Capítulos', 'bible.shortChapterCount': `${values.count} cap.`, 'bible.openReference': `Abrir ${values.reference}`,
}[key] ?? key) }) }))
vi.mock('../settings/SettingsProvider', () => ({ useSettings: () => ({ settings: { bibleVersion: 'nbla' } }) }))
vi.mock('../reader/preloadReading', () => ({ preloadReading: vi.fn() }))

const trigger = () => screen.getByRole('button', { name: 'Seleccionar libro', exact: true })
const book = (name) => screen.getByRole('button', { name: new RegExp(`^${name} \\d+ cap\\.$`) })

describe('accordion passage picker', () => {
  beforeEach(() => {
    vi.spyOn(HTMLElement.prototype, 'getBoundingClientRect').mockReturnValue({ x: 40, y: 180, left: 40, top: 180, right: 320, bottom: 234, width: 280, height: 54 })
  })
  afterEach(() => { cleanup(); vi.restoreAllMocks() })

  it('keeps the expanded book named in the fixed header for long chapter lists', () => {
    render(<HomePassagePicker currentBookId={19} currentChapter={150} onGoToChapter={vi.fn()} />)
    fireEvent.click(trigger())
    expect(screen.getByRole('dialog').querySelector('header').textContent).toContain('Elegir una lectura')
    fireEvent.click(book('Salmos'))
    expect(screen.getByRole('dialog').querySelector('header').textContent).toContain('Salmos · Capítulos')
    fireEvent.click(screen.getByRole('button', { name: 'Nuevo Testamento', exact: true }))
    expect(screen.getByRole('dialog').querySelector('header').textContent).toContain('Elegir una lectura')
    fireEvent.click(book('Judas'))
    expect(screen.getByRole('dialog').querySelector('header').textContent).toContain('Judas · Capítulos')
  })

  it('starts clean with one selector and no chapter selector or submit button', () => {
    render(<HomePassagePicker onGoToChapter={vi.fn()} />)
    expect(trigger().getAttribute('aria-expanded')).toBe('false')
    expect(screen.getAllByRole('button')).toHaveLength(1)
    expect(screen.queryByRole('dialog')).toBeNull()
    fireEvent.click(trigger())
    expect(screen.getAllByRole('button').filter(node => node.hasAttribute('data-book-id'))).toHaveLength(39)
    expect(screen.getByRole('button', { name: 'Antiguo Testamento', exact: true }).getAttribute('aria-pressed')).toBe('true')
  })

  it('opens chapters inside the list and closes them with either the book name or its X', () => {
    render(<HomePassagePicker onGoToChapter={vi.fn()} />)
    fireEvent.click(trigger())
    fireEvent.click(screen.getByRole('button', { name: 'Nuevo Testamento', exact: true }))
    fireEvent.click(book('Juan'))
    expect(screen.getAllByRole('button', { name: /^Abrir Juan / })).toHaveLength(21)
    fireEvent.click(book('Juan'))
    expect(screen.queryByRole('button', { name: 'Abrir Juan 1', exact: true })).toBeNull()
    fireEvent.click(book('Juan'))
    fireEvent.click(screen.getByRole('button', { name: 'Cerrar: Juan' }))
    expect(book('Juan').getAttribute('aria-expanded')).toBe('false')
    expect(document.activeElement).toBe(book('Juan'))
    expect(screen.getByRole('dialog')).toBeTruthy()
  })

  it('expands only one book and immediately navigates from its chapter, including 150 and 1', () => {
    const navigate = vi.fn()
    render(<HomePassagePicker onGoToChapter={navigate} />)
    fireEvent.click(trigger())
    fireEvent.click(book('Salmos'))
    expect(screen.getAllByRole('button', { name: /^Abrir Salmos / })).toHaveLength(150)
    fireEvent.click(screen.getByRole('button', { name: 'Abrir Salmos 150', exact: true }))
    expect(navigate).toHaveBeenLastCalledWith(19, 150)
    expect(screen.queryByRole('dialog')).toBeNull()
    fireEvent.click(trigger())
    fireEvent.click(screen.getByRole('button', { name: 'Nuevo Testamento', exact: true }))
    fireEvent.click(book('Judas'))
    expect(screen.queryByRole('button', { name: /^Abrir Salmos / })).toBeNull()
    expect(screen.getAllByRole('button', { name: /^Abrir Judas / })).toHaveLength(1)
    fireEvent.click(screen.getByRole('button', { name: 'Abrir Judas 1' }))
    expect(navigate).toHaveBeenLastCalledWith(65, 1)
  })

  it('uses the same neutral selector in the reader and notifies immersion on open, close and unmount', () => {
    const onOpenChange = vi.fn()
    const bookTriggerRef = { current: null }
    const view = render(<HomePassagePicker compact bookTriggerRef={bookTriggerRef} onOpenChange={onOpenChange} onGoToChapter={vi.fn()} />)
    expect(screen.getByTestId('reader-passage-picker')).toBeTruthy()
    expect(bookTriggerRef.current).toBe(trigger())
    fireEvent.click(trigger())
    expect(onOpenChange).toHaveBeenLastCalledWith(true)
    fireEvent.keyDown(trigger(), { key: 'Escape' })
    expect(onOpenChange).toHaveBeenLastCalledWith(false)
    expect(document.activeElement).toBe(trigger())
    fireEvent.click(trigger())
    view.unmount()
    expect(onOpenChange).toHaveBeenLastCalledWith(false)
  })

  it('supports keyboard book navigation and typeahead with spaces without selecting a chapter', () => {
    const navigate = vi.fn()
    render(<HomePassagePicker onGoToChapter={navigate} />)
    act(() => trigger().focus())
    fireEvent.keyDown(trigger(), { key: 'ArrowDown' })
    expect(document.activeElement).toBe(book('Génesis'))
    fireEvent.keyDown(document.activeElement, { key: 'End' })
    expect(document.activeElement).toBe(book('Malaquías'))
    fireEvent.keyDown(document.activeElement, { key: 'ArrowDown' })
    expect(document.activeElement).toBe(book('Malaquías'))
    for (const key of '1 Corintios') {
      fireEvent.keyDown(document.activeElement, { key })
      if (key === ' ') expect(fireEvent.keyUp(document.activeElement, { key })).toBe(false)
    }
    expect(document.activeElement).toBe(book('1 Corintios'))
    expect(screen.getByRole('button', { name: 'Nuevo Testamento', exact: true }).getAttribute('aria-pressed')).toBe('true')
    expect(navigate).not.toHaveBeenCalled()
    fireEvent.click(document.activeElement)
    expect(screen.getAllByRole('button', { name: /^Abrir 1 Corintios / })).toHaveLength(16)
  })

  it('dismisses the menu with its X, an outside pointer or focus leaving the whole control', () => {
    render(<HomePassagePicker onGoToChapter={vi.fn()} />)
    fireEvent.click(trigger())
    fireEvent.click(screen.getByRole('button', { name: 'Cerrar', exact: true }))
    expect(screen.queryByRole('dialog')).toBeNull()
    expect(document.activeElement).toBe(trigger())
    fireEvent.click(trigger())
    fireEvent.pointerDown(document.body)
    expect(screen.queryByRole('dialog')).toBeNull()
    fireEvent.click(trigger())
    fireEvent.blur(trigger(), { relatedTarget: document.body })
    expect(screen.queryByRole('dialog')).toBeNull()
  })

  it('keeps Safari button taps alive when focus moves to an ancestor of the popup', () => {
    const navigate = vi.fn()
    render(<HomePassagePicker onGoToChapter={navigate} />)
    fireEvent.click(trigger())
    fireEvent.click(screen.getByRole('button', { name: 'Nuevo Testamento', exact: true }))
    fireEvent.click(book('Juan'))
    const chapter = screen.getByRole('button', { name: 'Abrir Juan 3', exact: true })
    fireEvent.pointerDown(chapter)
    fireEvent.blur(book('Juan'), { relatedTarget: document.body })
    fireEvent.click(chapter)
    expect(navigate).toHaveBeenCalledExactlyOnceWith(43, 3)
  })

  it.each([[18, 20, 'Job', 'Antiguo Testamento', 39], [43, 3, 'Juan', 'Nuevo Testamento', 27]])('opens the current book %i collapsed and marks the chapter after explicit expansion', (bookId, chapter, name, testament, count) => {
    const navigate = vi.fn()
    render(<HomePassagePicker compact currentBookId={bookId} currentChapter={chapter} onGoToChapter={navigate} />)
    act(() => trigger().focus())
    fireEvent.click(trigger(), { detail: 1 })
    expect(book(name).getAttribute('aria-expanded')).toBe('false')
    expect(book(name).getAttribute('aria-current')).toBe('true')
    expect(screen.queryByRole('button', { name: /^Abrir / })).toBeNull()
    expect(screen.getByRole('button', { name: testament, exact: true }).getAttribute('aria-pressed')).toBe('true')
    expect(screen.getAllByRole('button').filter(node => node.hasAttribute('data-book-id'))).toHaveLength(count)
    expect(document.activeElement).toBe(trigger())
    expect(navigate).not.toHaveBeenCalled()
    fireEvent.click(book(name))
    expect(book(name).getAttribute('aria-expanded')).toBe('true')
    expect(screen.getByRole('button', { name: `Abrir ${name} ${chapter}`, exact: true }).getAttribute('aria-current')).toBe('page')
  })

  it('focuses the collapsed current book with arrows and keyboard activation', () => {
    render(<HomePassagePicker currentBookId={18} currentChapter={20} onGoToChapter={vi.fn()} />)
    fireEvent.keyDown(trigger(), { key: 'ArrowDown' })
    expect(document.activeElement).toBe(book('Job'))
    expect(book('Job').getAttribute('aria-expanded')).toBe('false')
    fireEvent.keyDown(document.activeElement, { key: 'Escape' })
    fireEvent.click(trigger(), { detail: 0 })
    expect(document.activeElement).toBe(book('Job'))
    expect(screen.queryByRole('button', { name: /^Abrir / })).toBeNull()
    fireEvent.click(book('Job'), { detail: 0 })
    expect(screen.getByRole('button', { name: 'Abrir Job 20', exact: true }).getAttribute('aria-current')).toBe('page')
  })

  it('changes testaments with keyboard controls without navigating or losing focus', () => {
    const navigate = vi.fn()
    const onOpenChange = vi.fn()
    render(<HomePassagePicker currentBookId={18} currentChapter={20} onGoToChapter={navigate} onOpenChange={onOpenChange} />)
    fireEvent.click(trigger())
    const old = screen.getByRole('button', { name: 'Antiguo Testamento', exact: true })
    const next = screen.getByRole('button', { name: 'Nuevo Testamento', exact: true })
    act(() => old.focus())
    fireEvent.keyDown(old, { key: 'ArrowRight' })
    expect(document.activeElement).toBe(next)
    expect(next.getAttribute('aria-pressed')).toBe('true')
    expect(screen.queryByRole('button', { name: /^Job / })).toBeNull()
    fireEvent.keyDown(next, { key: 'ArrowDown' })
    expect(document.activeElement).toBe(book('Mateo'))
    fireEvent.keyDown(document.activeElement, { key: 'ArrowUp' })
    expect(document.activeElement).toBe(book('Mateo'))
    fireEvent.keyDown(document.activeElement, { key: 'End' })
    expect(document.activeElement).toBe(book('Apocalipsis'))
    fireEvent.keyDown(document.activeElement, { key: 'Home' })
    expect(document.activeElement).toBe(book('Mateo'))
    fireEvent.keyDown(next, { key: 'Home' })
    expect(document.activeElement).toBe(old)
    expect(book('Job').getAttribute('aria-expanded')).toBe('false')
    expect(book('Job').getAttribute('aria-current')).toBe('true')
    fireEvent.keyDown(old, { key: 'ArrowDown' })
    expect(document.activeElement).toBe(book('Job'))
    expect(navigate).not.toHaveBeenCalled()
    expect(onOpenChange.mock.calls).toEqual([[true]])
    fireEvent.keyDown(old, { key: 'Escape' })
    expect(document.activeElement).toBe(trigger())
    expect(onOpenChange).toHaveBeenLastCalledWith(false)
  })

  it.each([[18, 'Home', 'Génesis'], [18, 'End', 'Malaquías'], [43, 'Home', 'Mateo'], [43, 'End', 'Apocalipsis']])('honors %s/%s from the closed trigger instead of overriding it with the current book', (bookId, key, name) => {
    render(<HomePassagePicker currentBookId={bookId} currentChapter={3} onGoToChapter={vi.fn()} />)
    fireEvent.keyDown(trigger(), { key })
    expect(document.activeElement).toBe(book(name))
  })

  it('reopens Job after switching away to the New Testament and closing', () => {
    render(<HomePassagePicker currentBookId={18} currentChapter={20} onGoToChapter={vi.fn()} />)
    fireEvent.click(trigger(), { detail: 1 })
    const next = screen.getByRole('button', { name: 'Nuevo Testamento', exact: true })
    fireEvent.click(next)
    expect(next.getAttribute('aria-pressed')).toBe('true')
    fireEvent.keyDown(next, { key: 'Escape' })
    fireEvent.click(trigger(), { detail: 1 })
    expect(book('Job').getAttribute('aria-expanded')).toBe('false')
    expect(book('Job').getAttribute('aria-current')).toBe('true')
    expect(screen.queryByRole('button', { name: /^Abrir / })).toBeNull()
    expect(screen.getByRole('button', { name: 'Antiguo Testamento', exact: true }).getAttribute('aria-pressed')).toBe('true')
  })

  it('uses global typeahead from a closed picker and resets to the route on reopening', () => {
    render(<HomePassagePicker currentBookId={18} currentChapter={20} onGoToChapter={vi.fn()} />)
    for (const key of 'Juan') fireEvent.keyDown(document.activeElement === document.body ? trigger() : document.activeElement, { key })
    expect(document.activeElement).toBe(book('Juan'))
    fireEvent.keyDown(document.activeElement, { key: 'Escape' })
    fireEvent.click(trigger(), { detail: 1 })
    expect(book('Job').getAttribute('aria-expanded')).toBe('false')
    expect(screen.getByRole('button', { name: 'Antiguo Testamento', exact: true }).getAttribute('aria-pressed')).toBe('true')
  })

  it('collapses a manually expanded book on reopening and follows a newly searched book', () => {
    const view = render(<HomePassagePicker currentBookId={18} currentChapter={42} onGoToChapter={vi.fn()} />)
    fireEvent.click(trigger())
    fireEvent.click(book('Job'))
    expect(book('Job').getAttribute('aria-expanded')).toBe('true')
    fireEvent.keyDown(book('Job'), { key: 'Escape' })
    fireEvent.click(trigger())
    expect(book('Job').getAttribute('aria-expanded')).toBe('false')
    fireEvent.keyDown(book('Job'), { key: 'Escape' })
    view.rerender(<HomePassagePicker currentBookId={24} currentChapter={28} onGoToChapter={vi.fn()} />)
    fireEvent.click(trigger())
    expect(book('Jeremías').getAttribute('aria-current')).toBe('true')
    expect(book('Jeremías').getAttribute('aria-expanded')).toBe('false')
    expect(book('Job').getAttribute('aria-current')).toBeNull()
    expect(screen.queryByRole('button', { name: /^Abrir / })).toBeNull()
  })

  it.each([[18, 42, 'Job'], [19, 150, 'Salmos'], [24, 28, 'Jeremías'], [52, 3, '1 Tesalonicenses']])('reveals book %s below the testament buttons with 8px of space without scrolling the document', (bookId, chapter, name) => {
    const scroll = vi.spyOn(window, 'scrollBy').mockImplementation(() => {})
    vi.spyOn(HTMLElement.prototype, 'offsetHeight', 'get').mockImplementation(function () { return this.tagName === 'HEADER' ? 96 : 0 })
    vi.spyOn(HTMLElement.prototype, 'clientHeight', 'get').mockImplementation(function () { return this.dataset.pickerMenu ? 324 : 54 })
    HTMLElement.prototype.getBoundingClientRect.mockImplementation(function () {
      const menu = this.closest('[data-picker-menu]')
      const scrollTop = menu?.scrollTop ?? 0
      const chapterRow = this.dataset.chapter ? Math.floor((Number(this.dataset.chapter) - 1) / 6) : 0
      const top = this.dataset.pickerMenu ? 234 : this.dataset.bookId ? 234 + 96 + (Number(this.dataset.bookId) - 1) * 46 - scrollTop : this.dataset.chapter ? 234 + 96 + (bookId - 1) * 46 + 46 + chapterRow * 51 - scrollTop : 180
      const height = this.dataset.pickerMenu ? 324 : this.dataset.chapter ? 44 : 54
      return { x: 40, y: top, left: 40, top, right: 320, bottom: top + height, width: 280, height }
    })
    render(<HomePassagePicker currentBookId={bookId} currentChapter={chapter} onGoToChapter={vi.fn()} />)
    fireEvent.click(trigger(), { detail: 1 })
    const menu = screen.getByRole('dialog')
    const current = book(name).getBoundingClientRect()
    expect(book(name).getAttribute('aria-expanded')).toBe('false')
    expect(book(name).getAttribute('aria-current')).toBe('true')
    expect(screen.queryByRole('button', { name: /^Abrir / })).toBeNull()
    expect(menu.scrollTop).toBeGreaterThan(0)
    expect(current.top).toBeGreaterThanOrEqual(menu.getBoundingClientRect().top + menu.clientTop + 96 + 8)
    expect(current.bottom).toBeLessThanOrEqual(menu.getBoundingClientRect().top + menu.clientTop + menu.clientHeight - 8)
    expect(scroll).not.toHaveBeenCalled()
  })
})
